"""Generate a compact AST-based source index (`refs/INDEX.md`) to avoid full-file reads."""
from __future__ import annotations

import ast
import re
from pathlib import Path

GENERATED_PREFIX = "<!-- generated by kiln index-refs"

_CORE_NAME_WEIGHTS: tuple[tuple[str, int], ...] = (
    ("model.py", 120),
    ("attention.py", 118),
    ("engram.py", 116),
    ("sparse_mla.py", 114),
    ("mhc.py", 112),
    ("all_reduce_mhc.py", 95),
    ("mhc_boundary.py", 90),
    ("flashinfer_sparse.py", 85),
    ("model_state.py", 80),
    ("dspark.py", 75),
    ("flashmla.py", 70),
    ("moe", 60),
    ("decode", 50),
    ("step", 45),
)

_PRIORITY_METHODS: tuple[str, ...] = (
    "forward",
    "forward_cuda",
    "forward_native",
    "forward_decode",
    "forward_prefill",
    "forward_mqa",
    "forward_kv",
    "forward_q",
    "forward_unfinalized",
    "_forward",
    "_forward_decode",
    "_forward_prefill",
    "_forward_low_batch",
    "humming_forward",
    "apply",
    "compute_logits",
    "__init__",
)
_METHOD_ORDER = {name: i for i, name in enumerate(_PRIORITY_METHODS)}
_SKIP_METHODS_NVIDIA = {"forward_hip", "forward_xpu", "forward_cpu"}


def _normalize_token(text: str) -> str:
    s = text.lower().strip()
    s = re.sub(r"v(\d+)\.(\d+)", r"v\1\2", s)
    s = re.sub(r"[^a-z0-9]+", "_", s)
    return s.strip("_")


def _model_stems(model_hint: str | None) -> list[str]:
    """Produce ordered normalized stems from a model name or path (longest/most specific first)."""
    if not model_hint:
        return []
    tail = Path(model_hint.rstrip("/")).name or model_hint
    norm = _normalize_token(tail)
    if not norm:
        return []
    parts = [p for p in norm.split("_") if p]
    stems: list[str] = []
    for k in range(len(parts), 0, -1):
        cand = "_".join(parts[:k])
        if len(cand) >= 3 and cand not in stems:
            stems.append(cand)
    # Also try collapsing `v41` -> `v4` as a lower-priority fallback.
    for s in list(stems):
        m = re.sub(r"_v(\d)\d+", r"_v\1", s)
        if m != s and m not in stems:
            stems.append(m)
    return stems


def _engine_model_roots(refs_dir: Path, engine_hint: str | None) -> list[Path]:
    if engine_hint and engine_hint.startswith("sglang"):
        rels = ("sglang/srt/models", "vllm/models", "vllm/model_executor/models")
    else:
        rels = ("vllm/models", "vllm/model_executor/models", "sglang/srt/models")
    return [refs_dir / r for r in rels if (refs_dir / r).is_dir()]


def _find_target_root(
    refs_dir: Path,
    model_hint: str | None,
    engine_hint: str | None,
) -> tuple[Path, bool]:
    """Return (target_path, is_matched_package) for indexing."""
    stems = _model_stems(model_hint)
    roots = _engine_model_roots(refs_dir, engine_hint)
    best_score = -1
    best_path: Path | None = None

    for root in roots:
        for entry in sorted(root.iterdir()):
            if entry.name.startswith((".", "_")) or entry.name == "__pycache__":
                continue
            entry_norm = _normalize_token(entry.stem if entry.is_file() else entry.name)
            if not entry_norm:
                continue
            for idx, stem in enumerate(stems):
                score = -1
                if entry_norm == stem:
                    score = 1000 - idx * 20 + len(stem)
                elif entry_norm.startswith(stem) or stem.startswith(entry_norm):
                    score = 500 - idx * 20 + min(len(entry_norm), len(stem))
                elif stem in entry_norm:
                    score = 200 - idx * 20 + len(stem)
                if score > best_score:
                    best_score = score
                    best_path = entry

    if best_path is not None:
        return best_path, True
    if roots:
        return roots[0], False
    return refs_dir, False


def _core_filename_score(path: Path) -> int:
    name = path.name.lower()
    for pat, weight in _CORE_NAME_WEIGHTS:
        if pat == name:
            return weight
    for pat, weight in _CORE_NAME_WEIGHTS:
        if pat in name:
            return weight - 15
    return 0


def _collect_package_files(pkg_dir: Path) -> tuple[list[Path], bool, int]:
    """Collect and rank Python files inside a model directory, returning (files, nvidia_focused, skipped_deep)."""
    all_py = [p for p in pkg_dir.rglob("*.py") if "__pycache__" not in p.parts and "tests" not in p.parts]
    has_nvidia = any("nvidia" in p.relative_to(pkg_dir).parts for p in all_py)
    has_non_ampere_nv = any(
        "nvidia" in p.relative_to(pkg_dir).parts and "ampere" not in p.relative_to(pkg_dir).parts
        for p in all_py
    )

    candidates: list[tuple[tuple[int, int, int, int], Path]] = []
    skipped_deep = 0
    for p in all_py:
        rel_parts = p.relative_to(pkg_dir).parts
        if p.name == "__init__.py":
            continue
        if has_nvidia and "amd" in rel_parts:
            continue
        if has_non_ampere_nv and "ampere" in rel_parts:
            continue

        try:
            text = p.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        n_lines = text.count("\n") + 1
        core_score = _core_filename_score(p)
        if n_lines < 60 and core_score < 100:
            continue

        is_deep = "specialized_decode" in rel_parts
        if is_deep:
            skipped_deep += 1
        tier = 2 if is_deep else 0
        depth_penalty = len(rel_parts)
        candidates.append(((-tier, core_score, -depth_penalty, n_lines), p))

    candidates.sort(key=lambda item: item[0], reverse=True)
    return [p for _, p in candidates], has_nvidia, skipped_deep


def _resolve_local_layer_imports(
    refs_dir: Path,
    seed_files: list[Path],
    limit: int = 4,
) -> list[Path]:
    """Follow 1-hop `ast.ImportFrom` into `*/layers/*` files that exist under `refs_dir`."""
    candidates: dict[Path, int] = {}
    for seed in seed_files[:3]:
        try:
            tree = ast.parse(seed.read_text(encoding="utf-8", errors="ignore"))
        except (OSError, SyntaxError):
            continue
        for node in ast.walk(tree):
            if not isinstance(node, ast.ImportFrom) or not node.module:
                continue
            mod = node.module
            if not (".layers." in mod or mod.endswith(".layers")):
                continue
            if any(skip in mod for skip in (".quantization", ".rocm_", "layernorm", "attention_layer_base")):
                continue
            rel = Path(*mod.split("."))
            for cand in (refs_dir / f"{rel}.py", refs_dir / rel / "__init__.py"):
                if cand.is_file() and cand.name != "__init__.py":
                    n_lines = cand.read_text(encoding="utf-8", errors="ignore").count("\n") + 1
                    if n_lines >= 80:
                        candidates[cand] = max(candidates.get(cand, 0), _core_filename_score(cand) * 20 + n_lines)
                    break

    ranked = sorted(candidates.items(), key=lambda kv: (-kv[1], str(kv[0])))
    return [p for p, _ in ranked[:limit]]


def _summarize_file(path: Path, nvidia_focused: bool) -> tuple[int, int, list[str]]:
    """Parse `path` via AST and return (line_count, size_bytes, formatted_detail_lines)."""
    raw = path.read_text(encoding="utf-8", errors="ignore")
    n_lines = raw.count("\n") + 1
    size_bytes = len(raw.encode("utf-8", errors="ignore"))
    try:
        tree = ast.parse(raw)
    except SyntaxError:
        return n_lines, size_bytes, []

    public_classes: list[ast.ClassDef] = []
    private_large_classes: list[ast.ClassDef] = []
    pub_funcs: list[ast.FunctionDef | ast.AsyncFunctionDef] = []

    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            span = (node.end_lineno or node.lineno) - node.lineno + 1
            if not node.name.startswith("_"):
                public_classes.append(node)
            elif span >= 150:
                private_large_classes.append(node)
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith("_"):
            pub_funcs.append(node)

    def _class_rank(cls: ast.ClassDef) -> tuple[int, int, int]:
        has_fwd = any(
            isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef))
            and (m.name in _METHOD_ORDER and m.name != "__init__" or ("forward" in m.name and not m.name.startswith("_")))
            for m in cls.body
        )
        span = (cls.end_lineno or cls.lineno) - cls.lineno + 1
        return (1 if not cls.name.startswith("_") else 0, 1 if has_fwd else 0, span)

    all_classes = public_classes + private_large_classes
    all_classes.sort(key=_class_rank, reverse=True)
    chosen_classes = sorted(all_classes[:5], key=lambda c: c.lineno)
    details: list[str] = []

    for cls in chosen_classes:
        end_ln = cls.end_lineno or cls.lineno
        methods: list[tuple[int, int, str, int]] = []
        for m in cls.body:
            if not isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            if nvidia_focused and m.name in _SKIP_METHODS_NVIDIA:
                continue
            if m.name in _METHOD_ORDER or ("forward" in m.name and not m.name.startswith("_")):
                prio = _METHOD_ORDER.get(m.name, 50)
                methods.append((prio, m.lineno, m.name, m.lineno))
        methods.sort(key=lambda x: (x[0], x[1]))
        method_strs = [f"`{mname}`:{mln}" for _, _, mname, mln in methods[:4]]
        m_part = f" ({', '.join(method_strs)})" if method_strs else ""
        details.append(f"  - `{cls.name}` L{cls.lineno}-{end_ln}{m_part}")

    if len(chosen_classes) <= 2 and pub_funcs:
        long_funcs = [f for f in pub_funcs if ((f.end_lineno or f.lineno) - f.lineno + 1) >= 15]
        pool = long_funcs or pub_funcs
        pool_ranked = sorted(pool, key=lambda f: ((f.end_lineno or f.lineno) - f.lineno + 1, -f.lineno), reverse=True)
        picked_funcs = sorted(pool_ranked[:6], key=lambda f: f.lineno)
        fn_strs = [f"`{f.name}` L{f.lineno}-{f.end_lineno or f.lineno}" for f in picked_funcs]
        details.append(f"  - fns: {', '.join(fn_strs)}")

    return n_lines, size_bytes, details


def build_refs_index(
    refs_dir: str | Path,
    model_hint: str | None = None,
    engine_hint: str | None = None,
    max_lines: int = 85,
) -> str:
    """Build a compact Markdown source index for `refs_dir` within `max_lines`."""
    refs = Path(refs_dir)
    max_lines = max(10, int(max_lines))
    header_model = (model_hint or "auto").replace("-->", "").replace("\n", " ").strip() or "auto"

    target, matched_pkg = _find_target_root(refs, model_hint, engine_hint)
    nvidia_focused = True
    skipped_deep = 0

    if target.is_file():
        primary_files = [target]
    elif matched_pkg and target.is_dir():
        primary_files, nvidia_focused, skipped_deep = _collect_package_files(target)
    else:
        all_py = [
            p
            for p in sorted(refs.rglob("*.py"))
            if not any(part in p.parts for part in ("__pycache__", "tests", "benchmarks", "third_party"))
            and p.name != "__init__.py"
        ]
        all_py.sort(
            key=lambda p: (_core_filename_score(p), p.read_text(encoding="utf-8", errors="ignore").count("\n")),
            reverse=True,
        )
        primary_files = all_py[:12]

    extra_layers = _resolve_local_layer_imports(refs, primary_files, limit=4) if primary_files else []
    ordered_files: list[Path] = []
    seen_files: set[Path] = set()
    for p in [*primary_files[:12], *extra_layers]:
        if p not in seen_files:
            seen_files.add(p)
            ordered_files.append(p)

    header = [
        f"{GENERATED_PREFIX}; model={header_model} -->",
        "# Refs Source Index",
        "> Read this index first instead of whole >20KB files. Inspect ranges with `sed -n 'START,ENDp' refs/<path>`.",
        "",
    ]

    footer: list[str] = []
    model_cfg = refs / "model_cfg" / "config.json"
    if model_cfg.is_file():
        footer.append("- `model_cfg/config.json`: model architecture config (dimensions, layers, MoE/Engram/MLA params)")
    if matched_pkg and skipped_deep > 0:
        spec_rel = (target / "nvidia" / "specialized_decode")
        if spec_rel.is_dir():
            footer.append(
                f"- `{spec_rel.relative_to(refs)}/`: {skipped_deep} specialized decode kernel modules (inspect selectively by subdir)"
            )

    file_blocks: list[list[str]] = []
    for fpath in ordered_files:
        n_lines, size_bytes, details = _summarize_file(fpath, nvidia_focused=nvidia_focused)
        rel = fpath.relative_to(refs).as_posix()
        kb = max(1, round(size_bytes / 1024))
        block = [f"- `{rel}` ({n_lines}L, {kb}KB)", *details]
        file_blocks.append(block)

    lines = list(header)
    reserve_footer = len(footer) + (1 if footer else 0)
    budget = max(len(header), max_lines - reserve_footer)

    added_any = False
    for block in file_blocks:
        if len(lines) + len(block) <= budget:
            lines.extend(block)
            added_any = True
        elif not added_any and len(lines) + 1 <= max_lines:
            avail = max_lines - len(lines)
            lines.extend(block[:avail])
            added_any = True
            break

    if footer and len(lines) + 1 + len(footer) <= max_lines:
        lines.append("")
        lines.extend(footer)
    elif footer and len(lines) + len(footer) <= max_lines:
        lines.extend(footer)

    return "\n".join(lines[:max_lines]).rstrip() + "\n"


def ensure_refs_index(
    refs_dir: str | Path,
    model_hint: str | None = None,
    engine_hint: str | None = None,
    out_path: str | Path | None = None,
    max_lines: int = 85,
    force: bool = False,
) -> Path | None:
    """Write `refs/INDEX.md` if missing or stale (never overwriting a hand-written INDEX.md unless `force=True`)."""
    refs = Path(refs_dir)
    if not refs.is_dir():
        return None

    target = Path(out_path) if out_path else refs / "INDEX.md"
    header_model = (model_hint or "auto").replace("-->", "").replace("\n", " ").strip() or "auto"

    if target.exists() and not force:
        existing_first = target.read_text(encoding="utf-8", errors="ignore").splitlines()[:1]
        first = existing_first[0] if existing_first else ""
        if not first.startswith(GENERATED_PREFIX):
            return target
        m = re.search(r";\s*model=(.*?)\s*-->", first)
        if m and m.group(1) == header_model:
            return target

    content = build_refs_index(refs, model_hint=model_hint, engine_hint=engine_hint, max_lines=max_lines)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")
    return target
